                        self.rpc('update_my_rejected_pending_match',update,ACTORS[c]);self.rpc('resubmit_my_rejected_match',quote(match),ACTORS[c])
                        self.assertEqual(run('SELECT created_by FROM matches WHERE id='+quote(match),self.db),ACTORS[c])
                        self.rpc('confirm_match_by_opponent',quote(match),ACTORS[who]);self.assertEqual(self.events(match),4)
