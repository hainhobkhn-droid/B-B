    def test_my_matches_scope_and_positions(self):
        # Existing baseline history is preserved; new 24 fixtures vary creator and status.
        for i in range(24):
            match=self.create(ACTORS[i%4])
            if i%3==0:self.rpc('approve_match_active',quote(match),ADMIN)
            elif i%3==1:self.rpc('reject_match_by_opponent',quote(match)+",'Fixture rejection'",ACTORS[(i%4+2)%4])
        for i,actor in enumerate(ACTORS):
            data=self.rpc('get_my_matches',actor=actor)
            expected=json.loads(run("SELECT coalesce(jsonb_agg(DISTINCT match_id),'[]') FROM match_players WHERE player_id="+quote(IDS[i])+" OR partner_player_id="+quote(IDS[i]),self.db))
