def quote(value):
    return "'"+str(value).replace("'","''")+"'"


def call(sql,db):
    return subprocess.run([PSQL,'-X','-w','-h','127.0.0.1','-p','55439','-U','postgres','-d',db,
                           '-At','-v','ON_ERROR_STOP=1'],input=sql,encoding='utf8',capture_output=True,env=ENV,timeout=45)


def run(sql,db):
    p=call(sql,db)
    assert p.returncode==0,p.stderr
    return p.stdout.strip()


def insert_rows(table,rows):
    result=[]
    for row in rows:
        columns=','.join('"'+k+'"' for k in row)
        values=','.join('r."'+k+'"' for k in row)
        data=quote(json.dumps(row))
        result.append(f'INSERT INTO public.{table}({columns}) SELECT {values} FROM json_populate_record(NULL::public.{table},{data}::json) r;')
    return '\n'.join(result)


def fixture_schema():
    sql=['CREATE SCHEMA auth;',
         "CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;",
         "CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.role',true),'') $$;",
         'GRANT USAGE ON SCHEMA auth TO anon,authenticated,service_role;']
    types={(x['table'],x['column']):x['type'] for x in BASE['column_types']}
    tables=sorted({c['table_name'] for c in CAT['columns']})
    for table in tables:
        fields=[]
        for c in CAT['columns']:
            if c['table_name']!=table:continue
            name=c['column_name'];type_=types.get((table,name),c['data_type'])
            if type_=='ARRAY':type_=c['udt_name'].lstrip('_')+'[]'
            default=' DEFAULT '+c['column_default'] if c['column_default'] else ''
            if name in ['id','replay_order'] and type_ in ['bigint','integer'] and not default:
                default=' GENERATED BY DEFAULT AS IDENTITY'
            primary=' PRIMARY KEY' if name=='id' else ''
            required=' NOT NULL' if c['is_nullable']=='NO' else ''
            fields.append('"'+name+'" '+type_+default+required+primary)
        sql.append('CREATE TABLE public.'+table+'('+','.join(fields)+');')
    sql.append('ALTER TABLE public.rating_adjustments ADD UNIQUE(request_id);')
    players=[dict(p,full_name='Synthetic '+p['id'][:8]) for p in BASE['players']]
    matches=[{k:v for k,v in m.items() if k!='played_date'}|{'status':'APPROVED'} for m in BASE['matches']]
    profiles=[dict(id=a,full_name='Match synthetic',role=role,is_active=True,membership_status='APPROVED',must_change_password=forced,player_id=player)
              for a,role,forced,player in [(ADMIN,'ADMIN',False,None),(MEMBER,'MEMBER',False,IDS[0]),(OTHER,'MEMBER',False,IDS[2]),(FORCED,'MEMBER',True,IDS[1])]]
    for table,rows in [('players',players),('profiles',profiles),('rating_settings',BASE['settings']),
                       ('rating_match_weights',BASE['weights']),('matches',matches),
                       ('match_players',BASE['lineups']),('rating_events',BASE['events'])]:
        sql.append(insert_rows(table,rows))
    definitions=';\n'.join(f['definition'] for f in [f for f in CAT['functions'] if f['name'] in ['_approve_match_internal', '_generate_match_fund_internal', '_get_active_rating_version', '_rebuild_ratings_internal', 'confirm_match_by_opponent', 'correct_rating_adjustment', 'create_my_pending_match', 'create_pending_match', 'current_user_business_access_active', 'guard_match_mutation', 'guard_match_player_mutation', 'record_rating_adjustment', 'record_rating_adjustment_active', 'reject_match_by_opponent', 'resubmit_my_rejected_match', 'set_pending_match_players', 'update_my_rejected_pending_match', 'void_match', 'current_user_player_id', 'get_my_pending_match_confirmations', 'approve_match', 'approve_match_active', 'reject_pending_match']])+';\n'
    def preserve_body(match):
        body=match.group(1).replace('\\','\\\\').replace("'","''").replace('\r','\\r').replace('\n','\\n')
        return "AS E'"+body+"'"
    sql.append(re.sub(r'AS \$function\$(.*?)\$function\$',preserve_body,definitions,flags=re.S))
    selected=set(['_approve_match_internal', '_generate_match_fund_internal', '_get_active_rating_version', '_rebuild_ratings_internal', 'confirm_match_by_opponent', 'correct_rating_adjustment', 'create_my_pending_match', 'create_pending_match', 'current_user_business_access_active', 'guard_match_mutation', 'guard_match_player_mutation', 'record_rating_adjustment', 'record_rating_adjustment_active', 'reject_match_by_opponent', 'resubmit_my_rejected_match', 'set_pending_match_players', 'update_my_rejected_pending_match', 'void_match', 'current_user_player_id', 'get_my_pending_match_confirmations', 'approve_match', 'approve_match_active', 'reject_pending_match'])
    for f in CAT['functions']:
        if f['name'] not in selected:continue
        sig='public.'+f['signature']
        sql.append('REVOKE ALL ON FUNCTION '+sig+' FROM PUBLIC,anon,authenticated,service_role;')
        for role,key in [('authenticated','authenticated_execute'),('anon','anon_execute'),('service_role','service_execute')]:
            if f[key]:sql.append('GRANT EXECUTE ON FUNCTION '+sig+' TO '+role+';')
    for t in CAT['triggers']:
        if t['table'] in ['matches','match_players']:sql.append(t['definition']+';')
    return '\n'.join(sql)



