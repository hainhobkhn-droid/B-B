        # Simulate production source drift before a first migration apply.
        run('DROP FUNCTION get_my_matches(); DROP FUNCTION get_match_creator_context();',self.db)
        run(definition.replace('MEMBER_CREATED_MATCH_REQUIRED','DRIFTED_MEMBER_CREATED_MATCH_REQUIRED'),self.db)
